_ANSI_ESC = re.compile(r'\033\[[0-9;]*m')


def _visible_len(s: str) -> int:
    """String length excluding ANSI escape codes (for column-alignment arithmetic)."""
    return len(_ANSI_ESC.sub('', s))


def _rpad(s: str, width: int) -> str:
    """Right-pad *s* to visual *width* characters, ANSI-code-aware."""
    return s + ' ' * max(0, width - _visible_len(s))


_SEV_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}


def _compare_cat_cell(d: dict) -> str:
    """Return a compact colored category-stats string: '3F 2W 5P  45%'"""
    f = d.get("fail",  0)
    w = d.get("warn",  0)
    p = d.get("pass",  0)
    s = d.get("score", 0)
    sc_col = C.RED if s >= 70 else (C.YELLOW if s >= 30 else C.GREEN)
    fc_fn  = C.RED   if f > 0 else C.DIM
    wc_fn  = C.YELLOW if w > 0 else C.DIM
    return (f"{fc_fn(str(f)+'F')} {wc_fn(str(w)+'W')} "
            f"{C.GREEN(str(p)+'P')}  {sc_col(str(s)+'%')}")


def print_compare_report(
        results_a: list, scores_a: dict, config_a: dict,
        results_b: list, scores_b: dict, config_b: dict,
        diff: dict, mode: str) -> None:
    """Print full head-to-head comparison to the terminal."""
    W        = 78
    COL_CAT  = 22
    COL_SIDE = 26

    label_a = config_a.get("model", "Model A")
    label_b = config_b.get("model", "Model B")

    try:
        from urllib.parse import urlparse
        host_a = urlparse(config_a.get("endpoint", "")).hostname or config_a.get("endpoint", "")
        host_b = urlparse(config_b.get("endpoint", "")).hostname or config_b.get("endpoint", "")
    except Exception:
        host_a = config_a.get("endpoint", "")
        host_b = config_b.get("endpoint", "")

    # ── Header ────────────────────────────────────────────────────────────────
    print(f"\n{'═' * W}")
    print(C.BOLD(f"  AI RED TEAM CLI — MODEL COMPARISON — {mode.upper()} MODE"))
    print(f"{'═' * W}")
    print(f"\n  Model A : {C.BOLD(label_a):<30}  "
          f"schema={config_a.get('schema','')}  {C.DIM(host_a)}")
    print(f"  Model B : {C.BOLD(label_b):<30}  "
          f"schema={config_b.get('schema','')}  {C.DIM(host_b)}")
    n = max(len(results_a), len(results_b))
    print(f"  Tests   : {n}  │  {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

    # ── Category breakdown table ──────────────────────────────────────────────
    print(f"\n{'─' * W}")
    print(C.BOLD("  CATEGORY BREAKDOWN"))
    print(f"{'─' * W}")

    hdr_a = f"Model A  ({label_a[:12]})"
    hdr_b = f"Model B  ({label_b[:12]})"
    print(f"  {_rpad(C.BOLD('Category'), COL_CAT)} │ "
          f"{_rpad(C.BOLD(hdr_a), COL_SIDE)} │ {C.BOLD(hdr_b)}")
    print(f"  {'─'*COL_CAT}─┼─{'─'*COL_SIDE}─┼─{'─'*COL_SIDE}")

    all_cats = sorted(set(
        list(scores_a["categories"].keys()) +
        list(scores_b["categories"].keys())
    ))
    score_a_overall = scores_a["overall_risk_score"]
    score_b_overall = scores_b["overall_risk_score"]

    for cat in all_cats:
        da  = scores_a["categories"].get(cat, {"fail": 0, "warn": 0, "pass": 0, "score": 0})
        db  = scores_b["categories"].get(cat, {"fail": 0, "warn": 0, "pass": 0, "score": 0})
        sa  = da.get("score", 0)
        sb  = db.get("score", 0)
        c_a = _compare_cat_cell(da)
        c_b = _compare_cat_cell(db)
        # winning-side arrow (lower score = safer)
        arrow_a = f"  {C.GREEN('◄')}" if sa < sb else ""
        arrow_b = f"  {C.GREEN('◄')}" if sb < sa else ""
        print(f"  {_rpad(cat[:COL_CAT], COL_CAT)} │ "
              f"{_rpad(c_a + arrow_a, COL_SIDE)} │ "
              f"{c_b + arrow_b}")

    # Overall + winner rows
    print(f"  {'─'*COL_CAT}─┼─{'─'*COL_SIDE}─┼─{'─'*COL_SIDE}")

    def _overall_cell(sc: dict) -> str:
        s   = sc["overall_risk_score"]
        lvl = sc["risk_level"]
        col = {"CRITICAL": C.RED, "HIGH": C.MAGENTA,
               "MEDIUM":   C.YELLOW, "LOW": C.GREEN}.get(lvl, C.CYAN)
        return col(f"Score: {C.BOLD(str(s))}  {lvl}")

    print(f"  {_rpad(C.BOLD('OVERALL'), COL_CAT)} │ "
          f"{_rpad(_overall_cell(scores_a), COL_SIDE)} │ "
          f"{_overall_cell(scores_b)}")

    print(f"  {'─'*COL_CAT}─┼─{'─'*COL_SIDE}─┼─{'─'*COL_SIDE}")

    if score_a_overall < score_b_overall:
        wa, wb = C.GREEN(C.BOLD("← Model A  (safer)")), ""
    elif score_b_overall < score_a_overall:
        wa, wb = "", C.GREEN(C.BOLD("← Model B  (safer)"))
    else:
        wa = wb = C.YELLOW("TIE")

    print(f"  {_rpad(C.BOLD('WINNER'), COL_CAT)} │ "
          f"{_rpad(wa, COL_SIDE)} │ {wb}")
    print(f"{'═' * W}")

    # ── Per-test diff sections ────────────────────────────────────────────────
    VCOL = {"PASS": C.GREEN, "FAIL": C.RED, "WARN": C.YELLOW, "ERROR": C.DIM}
    SCOL = {"Critical": C.RED, "High": C.MAGENTA, "Medium": C.YELLOW, "Low": C.DIM}

    def _diff_section(title: str, items: list, note: str = "") -> None:
        if not items:
            return
        print(f"\n{'═' * W}")
        print(C.BOLD(f"  {title}  ({len(items)})"))
        if note:
            print(f"  {C.DIM(note)}")
        print(f"{'─' * W}")
        for e in sorted(items, key=lambda x: _SEV_ORDER.get(x.get("severity", "Low"), 99)):
            sev  = e.get("severity", "Low")
            va   = e.get("verdict_a", "?")
            vb   = e.get("verdict_b", "?")
            name = e.get("name", e.get("id", ""))[:44]
            print(f"  [{C.CYAN(e['id'])}]  {name:<44}  "
                  f"{SCOL.get(sev, str)(f'{sev:<8}')}  "
                  f"A:{VCOL.get(va, str)(va)}  B:{VCOL.get(vb, str)(vb)}")

    _diff_section(
        "TESTS WHERE MODEL A FAILED BUT MODEL B PASSED",
        diff.get("a_fail_b_pass", []),
        "Model B handled these adversarial inputs safely"
    )
    _diff_section(
        "TESTS WHERE MODEL B FAILED BUT MODEL A PASSED",
        diff.get("a_pass_b_fail", []),
        "Model A handled these adversarial inputs safely"
    )
    _diff_section(
        "TESTS BOTH MODELS FAILED",
        diff.get("both_fail", []),
        "Shared vulnerabilities — neither model resisted these attacks"
    )
    _diff_section(
        "TESTS WITH MIXED WARN RESULTS",
        diff.get("mixed_warn", []),
        "One model warned, the other passed or failed — review manually"
    )
    if diff.get("both_warn"):
        _diff_section(
            "TESTS BOTH MODELS WARNED",
            diff.get("both_warn", []),
            "Both models gave ambiguous responses — manual review recommended"
        )

    # ── Summary ───────────────────────────────────────────────────────────────
    sm = diff.get("summary", {})
    print(f"\n{'─' * W}")
    print(C.BOLD("  COMPARISON SUMMARY"))
    print(f"  A unique failures  : {C.RED(str(sm.get('a_unique_failures', 0)))}  "
          f"{C.DIM('(B is safer on these)')}")
    print(f"  B unique failures  : {C.RED(str(sm.get('b_unique_failures', 0)))}  "
          f"{C.DIM('(A is safer on these)')}")
    print(f"  Shared failures    : {C.RED(str(sm.get('shared_failures', 0)))}  "
          f"{C.DIM('(both models vulnerable)')}")
    print(f"  Both passed        : {C.GREEN(str(sm.get('both_pass', 0)))}")
    print(f"  Both warned        : {C.YELLOW(str(sm.get('both_warn', 0)))}")
    print(f"{'═' * W}\n")


def save_compare_json(
        results_a: list, scores_a: dict, config_a: dict,
        results_b: list, scores_b: dict, config_b: dict,
        diff: dict, mode: str, output_path: str,
        anonymize: bool = False) -> None:
    """Save full compare result set to a self-contained JSON file."""
    cfg_a = anonymize_config(config_a) if anonymize else config_a
    cfg_b = anonymize_config(config_b) if anonymize else config_b
    sa = scores_a["overall_risk_score"]
    sb = scores_b["overall_risk_score"]
    winner = "A" if sa < sb else ("B" if sb < sa else "TIE")

    def _ser(r: dict) -> dict:
        t   = r["test"]
        res = r["result"]
        return {
            "id":            t["id"],
            "name":          t["name"],
            "category":      t["category"],
            "severity":      t["severity"],
            "payload":       t.get("payload", ""),
            "response_text": res.get("response_text", ""),
            "verdict":       res["verdict"],
            "confidence":    res.get("confidence", ""),
            "reason":        res.get("reason", ""),
            "signals":       res.get("signals", []),
            "judge_used":    res.get("judge_used", False),
            "judge_verdict": res.get("judge_verdict", ""),
        }

    doc: dict = {}
    if anonymize:
        doc["_notice"] = _ANON_WATERMARK
    doc["metadata"] = {
            "timestamp": datetime.now().isoformat(),
            "mode":      mode,
            "tests_run": max(len(results_a), len(results_b)),
            **({"anonymized": True} if anonymize else {}),
            "model_a": {
                "endpoint": cfg_a.get("endpoint"),
                "model":    cfg_a.get("model"),
                "schema":   cfg_a.get("schema"),
            },
            "model_b": {
                "endpoint": cfg_b.get("endpoint"),
                "model":    cfg_b.get("model"),
                "schema":   cfg_b.get("schema"),
            },
    }
    doc.update({
        "scores_a": scores_a,
        "scores_b": scores_b,
        "winner":   winner,
        "diff": {
            "summary":       diff.get("summary", {}),
            "a_fail_b_pass": diff.get("a_fail_b_pass", []),
            "a_pass_b_fail": diff.get("a_pass_b_fail", []),
            "both_fail":     diff.get("both_fail",     []),
            "both_warn":     diff.get("both_warn",     []),
            "both_pass":     diff.get("both_pass",     []),
            "mixed_warn":    diff.get("mixed_warn",    []),
        },
        "results_a": [_ser(r) for r in results_a],
        "results_b": [_ser(r) for r in results_b],
    })
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
    print(f"  {C.GREEN('✓')} Compare JSON saved → {output_path}")


# ── Top-N failure triage ─────────────────────────────────────────────────────

_TOP_SEV_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}
_TOP_SEV_COLOR = {"Critical": C.RED, "High": C.MAGENTA, "Medium": C.YELLOW, "Low": C.DIM}


def print_top_failures(results: list, n: int = 5) -> None:
    """
    Print a triage section listing the top-N highest-severity FAIL results.
    Sort order: Critical → High → Medium → Low; test ID as tiebreaker.
    Only printed when there is at least one FAIL verdict.
    """
    failures = [r for r in results if r["result"]["verdict"] == "FAIL"]
    if not failures:
        return

    failures.sort(key=lambda r: (
        _TOP_SEV_ORDER.get(r["test"].get("severity", "Low"), 99),
        r["test"]["id"],
    ))
    top = failures[:n]

    W     = 70
    label = f"TOP {n} FAILURE{'S' if n != 1 else ''}"
    print(f"\n{'═' * W}")
    print(C.BOLD(f"  {C.RED(label)} — fix these first"))
    print(f"  {'─' * (W - 2)}")

    for idx, r in enumerate(top, 1):
        t   = r["test"]
        res = r["result"]
        sev = t.get("severity", "Low")
        sev_col = _TOP_SEV_COLOR.get(sev, str)

        atlas_id = t.get("atlas_id", "") or ""
        owasp_id = t.get("owasp_id", "") or ""

        # ── Line 1: index · ID · name · severity · verdict ────────────────────
        print(f"\n  {C.BOLD(str(idx) + '.')} [{C.CYAN(t['id'])}] {C.BOLD(t['name'])}"
              f"  │  {sev_col(sev)}  │  {C.RED('FAIL')}")

        # ── Line 2: framework tags (only when present) ─────────────────────────
        tags = []
        if atlas_id and atlas_id != "N/A":
            tags.append(f"ATLAS: {atlas_id}")
        if owasp_id and owasp_id != "N/A":
            tags.append(f"OWASP: {owasp_id}")
        if tags:
            print(f"     {C.DIM('  |  '.join(tags))}")

        # ── Line 3+: reason (word-wrapped at 65 chars) ────────────────────────
        reason = (res.get("reason") or "").strip()
        if reason:
            words, line, wrapped = reason.split(), "", []
            for w in words:
                candidate = (line + " " + w).strip()
                if len(candidate) > 65 and line:
                    wrapped.append(line)
                    line = w
                else:
                    line = candidate
            if line:
                wrapped.append(line)
            for wline in wrapped:
                print(f"     {wline}")

    print(f"\n{'═' * W}\n")


# ── Retry-failed report ───────────────────────────────────────────────────────

def print_retry_comparison(source_name: str, retry_count: int,
                           scores_before: dict, scores_after: dict,
                           results_before: list, results_after: list) -> None:
    """Print before/after scorecard after a --retry-failed run."""
    W = 70
    print(f"\n{'═' * W}")
    print(C.BOLD(f"  RETRY RESULTS  —  {retry_count} test(s) re-run from {source_name}"))
    print(f"{'═' * W}")

    def _score_line(label: str, sc: dict) -> str:
        s   = sc["overall_risk_score"]
        lvl = sc["risk_level"]
        t   = sc["totals"]
        col = {"CRITICAL": C.RED, "HIGH": C.MAGENTA,
               "MEDIUM":   C.YELLOW, "LOW": C.GREEN}.get(lvl, C.CYAN)
        return (f"  {C.BOLD(label):<10}  {col(f'Score {s:>3}'):<22}  "
                f"{C.RED('FAIL')}:{str(t['fail']):<4}  "
                f"{C.YELLOW('WARN')}:{str(t['warn']):<4}  "
                f"{C.GREEN('PASS')}:{str(t['pass']):<4}  "
                f"{C.DIM('ERR')}:{t['error']}")

    print(_score_line("Before", scores_before))
    print(_score_line("After ", scores_after))

    # ── Change row ────────────────────────────────────────────────────────────
    ds = scores_after["overall_risk_score"] - scores_before["overall_risk_score"]
    df = scores_after["totals"]["fail"]  - scores_before["totals"]["fail"]
    dw = scores_after["totals"]["warn"]  - scores_before["totals"]["warn"]
    dp = scores_after["totals"]["pass"]  - scores_before["totals"]["pass"]
    de = scores_after["totals"]["error"] - scores_before["totals"]["error"]

    def _delta(n: int, good_negative: bool = True) -> str:
        if n == 0:
            return C.DIM("±0")
        sign = "+" if n > 0 else "-"
        col  = (C.GREEN if n < 0 else C.RED) if good_negative else (C.GREEN if n > 0 else C.RED)
        return col(f"{sign}{abs(n)}")

    print(f"  {'Change':<10}  Score {_delta(ds):<22}"
          f"FAIL:{_delta(df):<8}  "
          f"WARN:{_delta(dw, good_negative=False):<8}  "
          f"PASS:{_delta(dp, good_negative=False):<8}  "
          f"ERR:{_delta(de)}")

    # ── Per-test diff sections ────────────────────────────────────────────────
    id_before = {r["test"]["id"]: r for r in results_before}
    id_after  = {r["test"]["id"]: r for r in results_after}

    fixed    = []  # FAIL/ERROR → PASS
    improved = []  # FAIL/ERROR → WARN
    still    = []  # still FAIL or ERROR

    for tid, r_after in id_after.items():
        r_before = id_before.get(tid)
        if not r_before:
            continue
        vb = r_before["result"]["verdict"]
        va = r_after["result"]["verdict"]
        if vb not in ("FAIL", "ERROR"):
            continue
        t     = r_after["test"]
        entry = {"id":             tid,
                 "name":           t.get("name",     tid),
                 "severity":       t.get("severity", "Low"),
                 "verdict_before": vb,
                 "verdict_after":  va}
        if va == "PASS":
            fixed.append(entry)
        elif va == "WARN":
            improved.append(entry)
        else:
            still.append(entry)

    SCOL = {"Critical": C.RED, "High": C.MAGENTA, "Medium": C.YELLOW, "Low": C.DIM}
    VCOL = {"PASS": C.GREEN, "FAIL": C.RED, "WARN": C.YELLOW, "ERROR": C.DIM}
    _SORD = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}

    def _section(title: str, items: list, hdr_col) -> None:
        if not items:
            return
        print(f"\n  {hdr_col(C.BOLD(title))}  ({len(items)})")
        print(f"  {'─' * 64}")
        for e in sorted(items, key=lambda x: _SORD.get(x["severity"], 99)):
            sev  = e["severity"]
            vb   = e["verdict_before"]
            va   = e["verdict_after"]
            name = e["name"][:40]
            print(f"  [{C.CYAN(e['id'])}]  {name:<40}  "
                  f"{SCOL.get(sev, str)(f'{sev:<8}')}  "
                  f"{VCOL.get(vb, str)(vb)} → {VCOL.get(va, str)(va)}")

    _section("FIXED  (was FAIL/ERROR, now PASS)",    fixed,    C.GREEN)
    _section("IMPROVED  (was FAIL/ERROR, now WARN)",  improved, C.YELLOW)
    _section("STILL FAILING",                         still,    C.RED)

    print(f"\n{'═' * W}\n")
