        story.append(Paragraph("OWASP LLM Top 10 (2025) Coverage", s_h2))
        owasp_rows = [["ID", "Category", "Risk", "PASS", "FAIL", "WARN"]]
        for oid, data in owasp_cov.items():
            if oid == "N/A":
                continue
            owasp_rows.append([
                oid, (data.get("name", "") or "")[:34], data.get("risk", ""),
                str(data.get("pass", 0)), str(data.get("fail", 0)),
                str(data.get("warn", 0)),
            ])
